export function isAppLanguage(value: unknown): value is AppLanguage {
  return LANGUAGE_OPTIONS.some((option) => option.code === value);
}
export function translate(language: AppLanguage, key: TranslationKey) {
  return translations[language][key] ?? ko[key];
}

export function translateFaqCategory(
  language: AppLanguage,
  category: string,
) {
  return faqCategoryTranslations[language][category] ?? category;
}

export function translateFaqQuestion(
  language: AppLanguage,
  id: string,
  fallback: string,
) {
  return faqQuestionTranslations[language][id] ?? fallback;
}
